const fs = require("fs");
const p = "src/pages/ResourcePage/ResourceDetailPage.tsx";
let s = fs.readFileSync(p, "utf8");
const startA = "  // 正文编辑子系统收口于 useResourceDetailContentEdit。\n";
const endA = "    onSaveContent,\n    onRecordUpdated,\n    setPreviewEntry,\n  });\n";
if (s.split(startA).length !== 2) throw new Error("start not unique");
if (s.split(endA).length !== 2) throw new Error("end not unique");
const i = s.indexOf(startA);
const j = s.indexOf(endA, i) + endA.length;
const block = s.slice(i, j);
s = s.slice(0, i) + "  // 正文编辑子系统（编辑态/保存双通道/高度自伸缩）收口于\n  // useResourceDetailContentEdit（在正文取材之后调用，见下方）。\n" + s.slice(j);
const anchor = "    textReloadKey,\n  });\n";
if (s.split(anchor).length !== 2) throw new Error("contentSource end anchor not unique: " + (s.split(anchor).length - 1));
s = s.replace(anchor, anchor + "\n" + block);
fs.writeFileSync(p, s);
console.log("moved, lines:", s.split("\n").length);
